import { describe, expect, it } from "vitest";
import { automationActorForGrant } from "./automation-actor.js";
import type { InternalMcpGrantContext } from "./internal-mcp-broker.js";

const grant = (command: string): InternalMcpGrantContext => ({
  profileId: "p",
  workspaceId: "w",
  sessionId: "s",
  panelId: "panel",
  command,
  tasksEnabled: true,
});
describe("automation agent privileges", () => {
  it.each([
    "claude --dangerously-skip-permissions --model opus",
    "codex --dangerously-bypass-approvals-and-sandbox -s danger-full-access",
    "copilot --allow-all-tools",
    "opencode --yolo",
    "gemini --yolo",
  ])("accepts the generated bypass command %s", (command) => {
    expect(automationActorForGrant(grant(command))).toEqual({
      kind: "agent",
      sessionId: "s",
      canSkipPermissions: true,
    });
  });
  it.each([
    "codex -s danger-full-access",
    "claude --model --dangerously-skip-permissions",
    "claude --append-system-prompt --dangerously-skip-permissions",
    "claude --dangerously-skip-permissions; echo bad",
    "unknown --yolo",
  ])("fails closed for %s", (command) => {
    expect(automationActorForGrant(grant(command)).canSkipPermissions).toBe(false);
  });
});
